# Builds moj-trening/loadfx.js: the load-model factors (MODEL LM1 section 2) of every shipped exercise, window.EXFX = { id: fx }.
# Input: one or more factor files { exId: fx } (load_factors.json in the private build inputs, next to exercises_final.json);
# later files win per exercise. The "why" notes and "src" stay out of the app (the app sets src itself). Then it runs
# tools/build/check_load.cjs and stops (exit 1) when the factors are not complete and valid for data.js.
# usage: python3 tools/build/build_loadfx.py <repo> <load_factors.json> [more.json ...]
import json, os, subprocess, sys
if len(sys.argv) < 3:
    sys.exit('usage: build_loadfx.py <repo> <load_factors.json> [more.json ...]')
REPO = sys.argv[1]
fx = {}
for p in sys.argv[2:]:
    d = json.load(open(p, encoding='utf-8'))
    if not isinstance(d, dict):
        sys.exit(p + ': expected an object { exId: factors }')
    fx.update(d)
KEYS = ['v', 'pat', 'mx', 'uni', 'ecc', 'prime', 'rw', 'bw', 'cpr', 'tier', 'rir', 'runM', 'runInt', 'tags']
out = {}
for k in sorted(fx):
    f = fx[k]
    out[k] = {q: f[q] for q in KEYS if q in f}
js = ('// Generated by tools/build/build_loadfx.py: load-model factors (LM1) of the shipped exercises. Not inside the exercise objects,\n'
      '// so no shipped exercise changes its content hash. app.js loadFx() checks every field and derives anything missing.\n'
      'window.EXFX = {\n' + ',\n'.join(json.dumps(k, ensure_ascii=False) + ':' + json.dumps(out[k], ensure_ascii=False, separators=(',', ':')) for k in out) + '\n};\n')
open(os.path.join(REPO, 'loadfx.js'), 'w', encoding='utf-8').write(js)
print('loadfx.js:', len(out), 'exercises')
r = subprocess.run(['node', os.path.join(REPO, 'tools', 'build', 'check_load.cjs'), REPO])
sys.exit(r.returncode)
