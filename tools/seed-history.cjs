// Writes seed-history.js: the fingerprints of every exercise, protocol and field session as shipped
// in earlier releases. On the phone, an item whose fingerprint is in this list was never edited,
// so the app may replace it with the improved version from data.js. Your edits are never replaced.
// SEED_STRUCT: per protocol, the structure fingerprint of each shipped version (everything but the doses)
// with the dose fingerprint of each of its exercises. A protocol where you only set doses still gets
// a newer structure; the doses you set are kept, the ones you never touched follow the new version.
// SEED_LAYOUT: per protocol, the fingerprint of the exercise list alone (order and members, no doses) of each shipped
// version. A new description reaches a protocol whose exercises you changed only while the shipped list never changed.
// Usage: node tools/seed-history.cjs v1.0 [v1.1 ...]   (git tags of earlier releases)
const { execFileSync } = require('child_process');
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const ctx = { window: {} }; ctx.globalThis = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'hash.js'), 'utf8'), ctx);
const hash = ctx.window.mtContentHash, structHash = ctx.window.mtStructHash, doseHash = ctx.window.mtDoseHash;
const refs = process.argv.slice(2);
if (!refs.length) { console.error('Give at least one git tag, e.g. v1.0'); process.exit(1); }
const out = { exercises: {}, protocols: {}, field: {} }, struct = { protocols: {} }, layout = { protocols: {} };
for (const ref of refs) {
  const src = execFileSync('git', ['show', ref + ':data.js'], { cwd: root, encoding: 'utf8', maxBuffer: 64 << 20 });
  const c = { window: {} }; vm.createContext(c); vm.runInContext(src, c);
  const seed = c.window.SEED || {};
  for (const coll of Object.keys(out)) for (const [id, item] of Object.entries(seed[coll] || {})) {
    const h = hash(item); (out[coll][id] = out[coll][id] || []); if (!out[coll][id].includes(h)) out[coll][id].push(h);
  }
  for (const [id, p] of Object.entries(seed.protocols || {})) {
    const m = struct.protocols[id] = struct.protocols[id] || {}, sh = structHash(p), doses = (p.items || []).map(doseHash).join(' ');
    (m[sh] = m[sh] || []); if (!m[sh].includes(doses)) m[sh].push(doses);
    const l = layout.protocols[id] = layout.protocols[id] || [], lh = structHash({ items: p.items || [] }); if (!l.includes(lh)) l.push(lh);
  }
}
const n = Object.values(out).reduce((a, m) => a + Object.keys(m).length, 0);
fs.writeFileSync(path.join(root, 'seed-history.js'), '// generated by tools/seed-history.cjs from ' + refs.join(', ') + '\nwindow.SEED_HISTORY = ' + JSON.stringify(out) + ';\nwindow.SEED_STRUCT = ' + JSON.stringify(struct) + ';\nwindow.SEED_LAYOUT = ' + JSON.stringify(layout) + ';\n');
console.log('seed-history.js: ' + n + ' items from ' + refs.join(', '));
